CREATE TABLE Peca(id INTEGER PRIMARY KEY, stock INTEGER NOT NULL CHECK(stock >= 0));
CREATE TABLE Modelo(id INTEGER PRIMARY KEY);
CREATE TABLE Compativel(peca INTEGER NOT NULL REFERENCES Peca(id),
