CREATE TABLE Uso(id INTEGER PRIMARY KEY, peca INTEGER NOT NULL REFERENCES Peca(id),
  modelo INTEGER NOT NULL REFERENCES Modelo(id), qtd INTEGER NOT NULL CHECK(qtd > 0));
